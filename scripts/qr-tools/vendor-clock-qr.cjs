#!/usr/bin/env node
'use strict';

// Bundle only the installed packages already pinned by this directory's lock.
// No bundler dependency, eval, runtime require or downloaded browser build.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '../..');
const modulesRoot = path.join(__dirname, 'node_modules');
const destination = path.join(root, 'cmd/clock_check/assets/vendor');
const lock = JSON.parse(fs.readFileSync(path.join(__dirname, 'package-lock.json'), 'utf8'));
const expected = {qrcode: '1.5.4', dijkstrajs: '1.0.3', jsqr: '1.4.0'};
const sha256 = bytes => crypto.createHash('sha256').update(bytes).digest('hex');

function build() {
  const packages = {};
  for (const [name, version] of Object.entries(expected)) {
    const installed = JSON.parse(fs.readFileSync(path.join(modulesRoot, name, 'package.json'), 'utf8'));
    const pinned = lock.packages['node_modules/' + name];
    if (installed.version !== version || pinned?.version !== version || !pinned.integrity) {
      throw new Error(`Expected installed and locked ${name}@${version}; run npm ci --ignore-scripts --prefix scripts/qr-tools.`);
    }
    packages[name] = {version, integrity: pinned.integrity};
  }
  const moduleSources = new Map();
  const sourceHashes = {};
  function include(id) {
    if (moduleSources.has(id)) return;
    if (!/^qrcode\/lib\/core\/[a-z-]+\.js$/.test(id) && id !== 'dijkstrajs/dijkstra.js') throw new Error('Unexpected encoder dependency: ' + id);
    const original = fs.readFileSync(path.join(modulesRoot, id), 'utf8');
    sourceHashes[id] = sha256(original);
    moduleSources.set(id, '');
    const transformed = original.replace(/\brequire\((['"])([^'"]+)\1\)/g, (_match, _quote, requested) => {
      let next;
      if (requested === 'dijkstrajs') next = 'dijkstrajs/dijkstra.js';
      else if (requested.startsWith('./')) next = path.posix.normalize(path.posix.join(path.posix.dirname(id), requested)) + (requested.endsWith('.js') ? '' : '.js');
      else throw new Error('Unexpected module import: ' + requested);
      include(next);
      return 'require(' + JSON.stringify(next) + ')';
    });
    moduleSources.set(id, transformed);
  }
  const entry = 'qrcode/lib/core/qrcode.js';
  include(entry);
  const body = [...moduleSources.keys()].sort().map(id =>
    JSON.stringify(id) + ': function(module, exports, require) {\n' + moduleSources.get(id) + '\n}'
  ).join(',\n');
  const encoder = '/* Generated by scripts/qr-tools/vendor-clock-qr.cjs. qrcode 1.5.4 + dijkstrajs 1.0.3; MIT licenses alongside. */\n' +
    '(function() {\n\'use strict\';\nconst modules = {\n' + body + '\n};\n' +
    'const cache = Object.create(null);\nfunction load(id) {\n' +
    '  if (cache[id]) return cache[id].exports;\n  if (!Object.hasOwn(modules, id)) throw new Error("Unknown QR module");\n' +
    '  const module = {exports: {}}; cache[id] = module; modules[id](module, module.exports, load); return module.exports;\n}\n' +
    'globalThis.QRCode = Object.freeze({create: load(' + JSON.stringify(entry) + ').create});\n})();\n';
  const files = new Map([
    ['qrcode.js', Buffer.from(encoder)],
    ['jsQR.js', fs.readFileSync(path.join(modulesRoot, 'jsqr/dist/jsQR.js'))],
    ['qrcode-LICENSE.txt', fs.readFileSync(path.join(modulesRoot, 'qrcode/license'))],
    ['dijkstrajs-LICENSE.txt', fs.readFileSync(path.join(modulesRoot, 'dijkstrajs/LICENSE.md'))],
    ['jsqr-LICENSE.txt', fs.readFileSync(path.join(modulesRoot, 'jsqr/LICENSE'))],
  ]);
  const manifest = {
    generator: 'scripts/qr-tools/vendor-clock-qr.cjs', packages,
    sourceSHA256: Object.fromEntries(Object.keys(sourceHashes).sort().map(key => [key, sourceHashes[key]])),
    assetSHA256: Object.fromEntries([...files].map(([name, data]) => [name, sha256(data)])),
  };
  files.set('manifest.json', Buffer.from(JSON.stringify(manifest, null, 2) + '\n'));
  return files;
}

function run(args) {
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) throw new Error('Only --check is accepted.');
  const check = args[0] === '--check';
  const files = build();
  if (!check) fs.mkdirSync(destination, {recursive: true});
  for (const [name, contents] of files) {
    const output = path.join(destination, name);
    if (check) {
      if (!fs.readFileSync(output).equals(contents)) throw new Error('Vendored QR asset differs: ' + name);
    } else fs.writeFileSync(output, contents);
  }
  process.stdout.write(check ? 'Pinned QR vendor files reproduce exactly.\n' : 'Pinned QR browser assets generated.\n');
}
if (require.main === module) {
  try { run(process.argv.slice(2)); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
module.exports = {build};
